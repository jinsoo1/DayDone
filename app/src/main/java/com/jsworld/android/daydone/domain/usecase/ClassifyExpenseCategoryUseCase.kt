        // 선언 순서로 돌면서 "더 긴 키워드"일 때만 교체 → 동률이면 앞 순서 유지
        for ((category, keywords) in DICTIONARY) {
            for (keyword in keywords) {
                if (keyword.length > bestLength && normalized.contains(keyword)) {
                    best = category
                    bestLength = keyword.length
                }
            }
        }
        return best
    }

